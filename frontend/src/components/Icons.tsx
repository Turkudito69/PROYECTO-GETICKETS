export type IconName = keyof typeof icons;

type CompatibleIconProps = Omit<LucideProps, 'size' | 'color'> & {
  name: IconName | (string & {});
  size?: number;
  color?: string;
};

function CompatibleIonicon({ name, size = 24, color = '#111827', ...props }: CompatibleIconProps) {
  const Icon = icons[name as IconName] ?? CircleAlert;
  return <Icon size={size} color={color} strokeWidth={2} {...props} />;
}

export const Ionicons = Object.assign(CompatibleIonicon, { glyphMap: icons });
